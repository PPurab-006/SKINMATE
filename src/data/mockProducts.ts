/**
 * Creates a fully verified Product record with safe Google search redirect URLs,
 * Open Beauty Facts or Brand Official image sources, and explicit data quality metadata.
 */
function createVerifiedProduct(raw: Omit<Product, 'googleSearchQuery' | 'googleSearchUrl'>): Product {
  const query = buildGoogleProductSearchQuery({
    brand: raw.brand,
    name: raw.name,
    variant: raw.variant || raw.exactVariant,
    size: raw.size
  });

  const url = buildGoogleProductSearchUrl(query);

  return {
    ...raw,
    googleSearchQuery: query,
    googleSearchUrl: url
  };
}

